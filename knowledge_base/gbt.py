def it_tolerance(dim_mm: float, grade: int = 7) -> int:
    """查询 GB/T 1800.2 IT 公差值（μm）。"""
    for (lo, hi), table in IT_GRADES.items():
        if lo <= dim_mm <= hi:
            return table.get(grade, table.get(7, 0))
    return 0


